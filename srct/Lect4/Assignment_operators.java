package Lect4;

public class Assignment_operators {
    public static void main(String[] args) {

        //assignment operator is used to assign values to the operators
        int a=20;
        int val;
        val=25;
        System.out.println(val);

        //val+=a means val = val+a
        val+=a;
        System.out.println(val);
    }
}
