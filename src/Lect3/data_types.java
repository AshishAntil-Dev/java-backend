package Lect3;

public class data_types {
    public static void main(String[] args) {

        //Boolean is used for true and false conditions
        boolean flag=true;
        System.out.println(flag);

        //byte can have a range of -127 to 128
        byte range;
        range=124;
        System.out.println(range);

        //short can have a range of -32768 and 32767
        short range2;
        range2=32765;
        System.out.println(range2);

        //int can have a range of 2^-31 to 2^31 -1
        int temp;
        temp=73834694;
        System.out.println(temp);

        //long can hold values from 2^-63 to (2^63)-1
        //after assigning value to long put L at the end of the number
        long ranges1;
        ranges1=645748570005454554L;
        System.out.println(ranges1);

        //double precision 64 bit floating point digit
        double number=42.3;
        System.out.println(number);

        //float me last me f lagana h
        float numbt=42.5f;
        System.out.println(numbt);

        //char is a 16 bit unicode character
        char letter='\u0051';
        System.out.println(letter);

       /*comments
       are ignored by
       java compilers
        */


    }
}
